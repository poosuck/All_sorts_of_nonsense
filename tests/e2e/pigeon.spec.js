test("shape editor deforms the real model, restores the original, persists and exports", async ({ page }, testInfo) => {
  const errors = [], requests = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("request", request => { if (/\.glb(?:\?|$)/.test(request.url())) requests.push(request.url()); });
  await page.goto("/pigeon?edit=1&frame=head-neck&view=left");
  const scene = page.getByTestId("pigeon-scene");
  await expect(scene).toHaveAttribute("data-ready", "true", { timeout: 45000 });
  const canvas = page.locator(".pigeon-viewport canvas");
  await page.addStyleTag({ content: ".study-heading { visibility:hidden; }" });
  const { createHash } = await import("node:crypto");
  const captureHash = async () => createHash("sha256").update(await canvas.screenshot()).digest("hex");
  const before = await captureHash();
  const slider = page.getByLabel("머리 높이", { exact: true });
  await slider.fill("-20");
  await slider.dispatchEvent("change");
  await expect(scene).toHaveAttribute("data-adjusted", "true");
  await expect(page.getByRole("button", { name: "실행 취소", exact: true })).toBeEnabled();
  const after = await captureHash();
  expect(after).not.toBe(before);
  await page.getByRole("button", { name: "실행 취소", exact: true }).click();
  await expect(slider).toHaveValue("0");
  expect(await captureHash()).toBe(before);
  await page.getByRole("button", { name: "다시 실행", exact: true }).click();
  expect(await captureHash()).toBe(after);
  await page.getByRole("button", { name: "원본 비교", exact: true }).click();
  await expect(slider).toBeDisabled();
  expect(await captureHash()).toBe(before);
  await page.getByRole("button", { name: "수정본 보기", exact: true }).click();
  expect(await captureHash()).toBe(after);
  await page.reload();
  await expect(scene).toHaveAttribute("data-ready", "true", { timeout: 45000 });
  await expect(slider).toHaveValue("-20");
  await page.addStyleTag({ content: ".study-heading { visibility:hidden; }" });
  expect(await captureHash()).toBe(after);

  const recipeDownload = page.waitForEvent("download");
  await page.getByRole("button", { name: "조정값 JSON 저장", exact: true }).click();
  const recipe = await recipeDownload;
  const { readFile } = await import("node:fs/promises");
  const recipeBytes = await readFile(await recipe.path());
  expect(JSON.parse(recipeBytes).values.headHeight).toBe(-20);
  await page.getByRole("button", { name: "모든 조정값을 0으로", exact: true }).click();
  await expect(slider).toHaveValue("0");
  await page.getByLabel("조정값 불러오기").setInputFiles({ name: "settings.json", mimeType: "application/json", buffer: recipeBytes });
  await expect(slider).toHaveValue("-20");
  const incompatible = JSON.parse(recipeBytes); incompatible.baseSha256 = "old-model";
  await page.getByLabel("조정값 불러오기").setInputFiles({ name: "wrong.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(incompatible)) });
  await expect(page.getByText("다른 버전 모델의 조정값입니다. 원본 버전이 같은 파일을 선택하세요.")).toBeVisible();
  await expect(slider).toHaveValue("-20");

  await page.getByRole("button", { name: "깃털 숨기기", exact: true }).click();
  const glbDownload = page.waitForEvent("download");
  await page.getByRole("button", { name: "수정 모델 GLB 저장", exact: true }).click();
  const glb = await glbDownload;
  const bytes = await readFile(await glb.path());
  expect(bytes.toString("ascii", 0, 4)).toBe("glTF");
  const json = JSON.parse(bytes.subarray(20, 20 + bytes.readUInt32LE(12)).toString());
  const edit = [...json.nodes, ...json.scenes].find(node => node.extras?.shapeEdit)?.extras.shapeEdit;
  expect(edit.values.headHeight).toBe(-20);
  expect(json.nodes.some(node => node.name === "Plumage_neck_gradient")).toBe(true);
  expect(json.meshes.length).toBe(48);
  await page.getByRole("button", { name: "깃털 보이기", exact: true }).click();
  await page.getByRole("button", { name: "전신", exact: true }).click();
  await page.getByText("시점·표면 선택", { exact: true }).click();
  await page.getByRole("button", { name: "좌측 45°", exact: true }).click();
  await page.addStyleTag({ content: ".study-heading { visibility:visible; }" });
  await page.screenshot({ path: testInfo.outputPath("shape-editor.png") });
  const pngDownload = page.waitForEvent("download");
  await page.getByRole("button", { name: "현재 화면 PNG 저장", exact: true }).click();
  const png = await pngDownload;
  const pngBytes = await readFile(await png.path());
  expect(pngBytes.subarray(1, 4).toString()).toBe("PNG");
  expect(pngBytes.length).toBeGreaterThan(10000);
  expect(requests).toHaveLength(2); // Initial visit + explicit reload only.
  await page.getByRole("button", { name: "편집 닫기", exact: true }).click();
  await expect(scene).toHaveAttribute("data-adjusted", "false");
  await page.getByRole("button", { name: "직접 형태 조정하기", exact: true }).click();
  await expect(slider).toHaveValue("-20");
  expect(errors).toEqual([]);
});

